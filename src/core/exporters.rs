use crate::core::query_ast::{FilterValue, QueryAst};
use crate::core::sql_compiler::{compile_to_tsql, CompileMode, ResolvedColumn};
use indoc::formatdoc;

/// รูปแบบภาษาเป้าหมายที่ต้องการส่งออกโค้ด
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ExportTarget {
    /// 1. คำสั่ง Pure T-SQL มาตรฐาน (นำไปใช้ได้กับทุกโปรแกรม/ฐานข้อมูล)
    PureSql,
    /// 2. โค้ด C# พร้อม SqlParameter[] (สำหรับโปรเจกต์ WinForms / ADO.NET)
    CSharp,
    /// 3. โค้ด TypeScript Interface + Query Payload (สำหรับงานเว็บ Vue / React / Node.js)
    TypeScript,
}

/// โครงสร้างเก็บพารามิเตอร์ที่ถูกสกัดออกมาจาก QueryAst
struct ExtractedParam {
    name: String,
    sample_value: String,
    is_numeric: bool,
}

/// แปลง QueryAst ให้เป็นซอร์สโค้ดตามภาษาเป้าหมายที่เลือก
pub fn export_query(ast: &QueryAst, target: ExportTarget) -> String {
    let compiled = compile_to_tsql(ast, CompileMode::Export);
    let params = extract_parameters(ast);

    match target {
        ExportTarget::PureSql => export_pure_sql(&compiled.sql, &params),
        ExportTarget::CSharp => export_csharp(&compiled.sql, &params),
        ExportTarget::TypeScript => {
            export_typescript(&ast.main_table.name, &compiled.sql, &compiled.resolved_columns, &params)
        }
    }
}

/// สกัดรายการ @Parameter ทั้งหมดที่ผู้ใช้สร้างไว้ในเงื่อนไข WHERE
fn extract_parameters(ast: &QueryAst) -> Vec<ExtractedParam> {
    let mut list = Vec::new();
    for cond in &ast.where_conditions {
        if let FilterValue::Parameter {
            param_name,
            sample_value,
            is_numeric,
        } = &cond.value
        {
            let clean_name = param_name.trim_start_matches('@').to_string();
            // ป้องกันการเก็บชื่อ Parameter ซ้ำ
            if !list.iter().any(|p: &ExtractedParam| p.name == clean_name) {
                list.push(ExtractedParam {
                    name: clean_name,
                    sample_value: sample_value.clone().unwrap_or_default(),
                    is_numeric: *is_numeric,
                });
            }
        }
    }
    list
}

// =========================================================================
// Target 1: Pure SQL (Pattern กลาง ใช้ได้กับทุกระบบ)
// =========================================================================
fn export_pure_sql(sql: &str, params: &[ExtractedParam]) -> String {
    let mut output = String::new();
    output.push_str("-- Generated by qcraft\n");

    if !params.is_empty() {
        output.push_str("-- Parameters Required:\n");
        for p in params {
            let val_hint = if p.is_numeric {
                p.sample_value.clone()
            } else {
                format!("N'{}'", p.sample_value)
            };
            output.push_str(&format!("--   DECLARE @{} = {};\n", p.name, val_hint));
        }
        output.push('\n');
    }

    output.push_str(sql);
    output.push(';');
    output
}

// =========================================================================
// Target 2: C# (สำหรับ WinForms / ADO.NET DbHelper)
// =========================================================================
fn export_csharp(sql: &str, params: &[ExtractedParam]) -> String {
    // จัดย่อหน้า SQL ให้อยู่ใน C# Verbatim String (@"...") อย่างสวยงาม
    let indented_sql: String = sql
        .lines()
        .map(|line| format!("    {}", line))
        .collect::<Vec<_>>()
        .join("\n");

    if params.is_empty() {
        formatdoc!(
            r#"
            // Generated by qcraft (C# ADO.NET)
            string sql = @"
            {indented_sql}";

            DataTable dt = _db.GetDataTable(sql);
            "#,
            indented_sql = indented_sql
        )
    } else {
        let mut param_lines = Vec::new();
        for p in params {
            let default_val = if p.sample_value.is_empty() {
                "DBNull.Value".to_string()
            } else if p.is_numeric {
                p.sample_value.clone()
            } else {
                format!("\"{}\"", p.sample_value)
            };
            param_lines.push(format!(
                "    new SqlParameter(\"@{}\", {})",
                p.name, default_val
            ));
        }

        formatdoc!(
            r#"
            // Generated by qcraft (C# ADO.NET with Parameters)
            string sql = @"
            {indented_sql}";

            SqlParameter[] parameters = new[]
            {{
            {params_block}
            }};

            DataTable dt = _db.GetDataTable(sql, parameters);
            "#,
            indented_sql = indented_sql,
            params_block = param_lines.join(",\n")
        )
    }
}

// =========================================================================
// Target 3: TypeScript (สำหรับงานเว็บ Vue / React / Node.js)
// =========================================================================
fn export_typescript(
    main_table: &str,
    sql: &str,
    columns: &[ResolvedColumn],
    params: &[ExtractedParam],
) -> String {
    let interface_name = format!("{}Result", to_pascal_case(main_table));

    let mut fields = Vec::new();
    for col in columns {
        let ts_type = map_sql_to_ts_type(&col.sql_data_type);
        let prop_name = to_camel_case(&col.final_name);
        fields.push(format!("  {}: {}; // DB: {} ({})", prop_name, ts_type, col.final_name, col.sql_data_type));
    }

    let param_interface = if params.is_empty() {
        String::new()
    } else {
        let p_fields: Vec<String> = params
            .iter()
            .map(|p| {
                let ts_t = if p.is_numeric { "number" } else { "string" };
                format!("  {}: {};", to_camel_case(&p.name), ts_t)
            })
            .collect();

        format!(
            "\nexport interface {}Params {{\n{}\n}}\n",
            to_pascal_case(main_table),
            p_fields.join("\n")
        )
    };

    formatdoc!(
        r#"
        // Generated by qcraft (TypeScript / Vue / React)
        export interface {interface_name} {{
        {fields_block}
        }}
        {param_interface}
        export const querySql = `
        {sql}
        `;
        "#,
        interface_name = interface_name,
        fields_block = fields.join("\n"),
        param_interface = param_interface,
        sql = sql
    )
}

fn map_sql_to_ts_type(sql_type: &str) -> &'static str {
    match sql_type.to_lowercase().as_str() {
        "int" | "bigint" | "smallint" | "tinyint" | "decimal" | "numeric" | "money" | "float" | "real" => "number",
        "bit" => "boolean",
        "datetime" | "datetime2" | "date" | "datetimeoffset" => "string | Date",
        _ => "string",
    }
}

fn to_pascal_case(s: &str) -> String {
    let mut res = String::new();
    let mut cap = true;
    for c in s.chars() {
        if c == '_' || c == '-' || c == ' ' {
            cap = true;
        } else if cap {
            res.extend(c.to_uppercase());
            cap = false;
        } else {
            res.push(c);
        }
    }
    res
}

fn to_camel_case(s: &str) -> String {
    let pascal = to_pascal_case(s);
    let mut chars = pascal.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => first.to_lowercase().collect::<String>() + chars.as_str(),
    }
}
